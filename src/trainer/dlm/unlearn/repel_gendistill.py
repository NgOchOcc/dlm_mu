"""Repel and secret-free generative distillation for masked-diffusion LMs.

The trainer caches two values per forget example: prompt-dependent positions
selected by PCSS and a secret-free answer generated by the frozen model. Each
training draw combines whole-answer distillation with RBF embedding repulsion::

    loss = repel_alpha * repel_loss + (1 - repel_alpha) * distill_loss

Teacher work is globally gated so every ZeRO-3 rank executes the same sequence
of collective operations, including when only some ranks have cache misses.
"""

import math
import re

import torch
import torch.distributed as dist
import torch.nn.functional as F

from trainer.dlm.unlearn.grad_diff import DiffusionGD

_SPECIAL_RE = re.compile(r"<\|?[^<>]*\|?>")


def _group_word_indices(surfaces):
    """Group token positions into whitespace-delimited words, so a name split across
    subword tokens ("Hs"+"iao" -> "Hsiao") is matched as one word."""
    groups, cur = [], []
    for i, s in enumerate(surfaces):
        if s[:1].isspace() and cur:
            groups.append(cur)
            cur = [i]
        else:
            cur.append(i)
    if cur:
        groups.append(cur)
    return groups


def _content_frags(surface, min_len=2):
    surface = _SPECIAL_RE.sub(" ", surface).lower()
    return [f for f in re.findall(r"[a-z0-9]+", surface) if len(f) >= min_len]


class DiffusionRDU(DiffusionGD):
    _QUERY_KEEP = {
        "what", "who", "which", "how", "when", "where", "why", "whose", "can", "could",
        "would", "does", "did", "do", "is", "are", "was", "were", "has", "have", "had",
        "the", "a", "an", "in", "on", "at", "of", "to", "for", "and", "or", "by", "with",
        "about", "that", "this", "his", "her", "their", "he", "she", "it", "they", "you",
        "some", "any", "one", "name", "full", "author", "genre", "born", "writes", "write",
        "book", "books", "work", "works", "novel", "novels", "writing", "career", "life",
        "father", "mother", "parents", "star", "wars",
    }

    def __init__(
        self,
        repel_alpha=0.5,
        sel_mc=8,
        select_method="otsu",
        topk_frac=0.3,
        tau=0.0,
        otsu_relax=0.0,
        drop_question_overlap=True,
        gen_steps=128,
        keep_answer=False,
        query_blank_identity=True,
        keep_subject_name=False,
        distill_mode="sft",
        distill_topk=64,
        suppress_gold=True,
        loss_d_ahat_weight=1.0,
        sigma="median",
        sigma_anc=1.0,
        sigma_fallback=0.05,
        gamma_anc=1.0,
        loss_mc=1,
        *args,
        **kwargs,
    ):
        super().__init__(*args, **kwargs)
        if not (0.0 <= repel_alpha <= 1.0):
            raise ValueError(f"repel_alpha must be in [0, 1], got {repel_alpha}")
        if select_method not in ("otsu", "tau", "topk"):
            raise ValueError(f"select_method must be otsu|tau|topk, got {select_method!r}")
        if distill_mode not in ("sft", "teacher"):
            raise ValueError(f"distill_mode must be sft|teacher, got {distill_mode!r}")
        if int(sel_mc) < 1:
            raise ValueError(f"sel_mc must be >= 1, got {sel_mc}")
        if int(loss_mc) < 1:
            raise ValueError(f"loss_mc must be >= 1, got {loss_mc}")
        if int(gen_steps) < 1:
            raise ValueError(f"gen_steps must be >= 1, got {gen_steps}")

        self.repel_alpha = float(repel_alpha)
        self.sel_mc = int(sel_mc)
        self.select_method = select_method
        self.topk_frac = float(topk_frac)
        self.tau = float(tau)
        self.otsu_relax = float(otsu_relax)
        self.drop_question_overlap = bool(drop_question_overlap)

        self.gen_steps = int(gen_steps)
        self.keep_answer = bool(keep_answer)
        self.query_blank_identity = bool(query_blank_identity)
        self.keep_subject_name = bool(keep_subject_name)

        self.distill_mode = distill_mode
        self.distill_topk = int(distill_topk)
        self.suppress_gold = bool(suppress_gold)
        self.loss_d_ahat_weight = float(loss_d_ahat_weight)

        median = isinstance(sigma, str) and str(sigma).lower() == "median"
        self.median_bandwidth = median
        self.sigma = None if median else float(sigma)
        self.sigma_anc = float(sigma_anc)
        self.sigma_fallback = float(sigma_fallback)
        self.gamma_anc = float(gamma_anc)

        self.loss_mc = int(loss_mc)

        self.mask_id = self.processing_class.mask_token_id
        self.pad_id = self.processing_class.pad_token_id
        self.vocab_size = len(self.processing_class)

        self.ref_model = self._prepare_ref_model(self.model)
        for p in self.ref_model.parameters():
            p.requires_grad_(False)

        self._ahat_cache = {}
        self._gen_cache = {}
        self._special_ids_cache = None
        self._eos_ids_cache = None
        self._pending_metrics = {}
        self._dbg_done = set()

    @torch.no_grad()
    def _teacher_logits(self, y, attention_mask):
        out = self.ref_model(input_ids=y, attention_mask=attention_mask)
        return self._postprocess_outputs(out).logits

    @torch.no_grad()
    def _teacher_log_probs(self, y, attention_mask):
        return self._log_probs(self._teacher_logits(y, attention_mask))

    def _prompt_mask(self, input_ids, answer_mask, attention_mask):
        """Prompt positions to blank for the promptless anchor / x_empty: attended,
        non-answer, non-pad tokens."""
        prompt = (~answer_mask) & (input_ids != self.pad_id)
        if attention_mask is not None:
            prompt = prompt & attention_mask.bool()
        return prompt

    def _identity_mask(self, input_ids, answer_mask, attention_mask):
        if self.query_blank_identity:
            return self._query_identity_mask(input_ids, answer_mask, attention_mask)
        return self._query_shared_mask(input_ids, answer_mask, attention_mask)

    def _question_overlap_mask(self, input_ids, answer_mask, prompt):
        """Answer words that merely echo a question word (no secret to forget)."""
        tok = self.processing_class
        overlap = torch.zeros_like(answer_mask)
        for bi in range(input_ids.shape[0]):
            q_ids = input_ids[bi][prompt[bi]].tolist()
            if not q_ids:
                continue
            q_text = tok.decode(q_ids, skip_special_tokens=True).lower()
            qwords = {w for w in re.findall(r"[a-z0-9]+", q_text) if len(w) >= 2}
            if not qwords:
                continue
            ans_idx = answer_mask[bi].nonzero(as_tuple=True)[0]
            if ans_idx.numel() == 0:
                continue
            surfaces = [tok.decode([int(t)]) for t in input_ids[bi][ans_idx]]
            for grp in _group_word_indices(surfaces):
                frags = _content_frags("".join(surfaces[j] for j in grp))
                if frags and all(f in qwords for f in frags):
                    for j in grp:
                        overlap[bi, ans_idx[j]] = True
        return overlap

    def _query_shared_mask(self, input_ids, answer_mask, attention_mask):
        """QUERY positions whose word ALSO appears in the answer -- the entity NAMES and
        shared TITLES that carry identity. Blanked in the teacher's generation context so
        it produces a coherent yet secret-free answer (a fully-masked query yields '. A. A.'
        filler)."""
        tok = self.processing_class
        prompt = self._prompt_mask(input_ids, answer_mask, attention_mask)
        shared = torch.zeros_like(answer_mask)
        for bi in range(input_ids.shape[0]):
            a_ids = input_ids[bi][answer_mask[bi]].tolist()
            if not a_ids:
                continue
            a_text = tok.decode(a_ids, skip_special_tokens=True).lower()
            awords = {w for w in re.findall(r"[a-z0-9]+", a_text) if len(w) >= 2}
            if not awords:
                continue
            q_idx = prompt[bi].nonzero(as_tuple=True)[0]
            if q_idx.numel() == 0:
                continue
            surfaces = [tok.decode([int(t)]) for t in input_ids[bi][q_idx]]
            for grp in _group_word_indices(surfaces):
                frags = _content_frags("".join(surfaces[j] for j in grp))
                if frags and all(f in awords for f in frags):
                    for j in grp:
                        shared[bi, q_idx[j]] = True
        return shared

    def _query_identity_mask(self, input_ids, answer_mask, attention_mask):
        """QUERY positions carrying IDENTITY -- proper-noun words (capitalized, non-
        sentence-initial, not a question/function word) and numeric/date tokens -- UNIONED
        with the query-shared mask. Blanks the name/place/date even when the answer refers
        to it only by pronoun/surname, so the teacher cannot reconstruct the true identity."""
        prompt = self._prompt_mask(input_ids, answer_mask, attention_mask)
        ident = self._query_shared_mask(input_ids, answer_mask, attention_mask).clone()
        tok = self.processing_class
        for bi in range(input_ids.shape[0]):
            q_idx = prompt[bi].nonzero(as_tuple=True)[0]
            if q_idx.numel() == 0:
                continue
            surfaces = [tok.decode([int(t)]) for t in input_ids[bi][q_idx]]
            prev_end = True
            for grp in _group_word_indices(surfaces):
                word = "".join(surfaces[j] for j in grp).strip()
                alpha = re.sub(r"[^A-Za-z]", "", word)
                has_digit = bool(re.search(r"\d", word))
                is_proper = (
                    len(alpha) >= 2 and alpha[0].isupper() and not prev_end
                    and word.lower() not in self._QUERY_KEEP
                )
                if is_proper or has_digit:
                    for j in grp:
                        ident[bi, q_idx[j]] = True
                prev_end = word.endswith((".", "!", "?", ":", ";"))
        return ident

    def _answer_name_mask(self, input_ids, answer_mask, attention_mask):
        """Entity NAME positions INSIDE the answer (keep-answer generation target): answer
        words echoing a query word, unioned with a capitalized non-sentence-initial proper-
        noun heuristic that also catches names appearing only in the answer."""
        prompt = self._prompt_mask(input_ids, answer_mask, attention_mask)
        names = self._question_overlap_mask(input_ids, answer_mask, prompt).clone()
        STOP = {"the", "a", "an", "in", "on", "at", "of", "for", "to", "she", "he", "it",
                "they", "his", "her", "their", "this", "that", "as", "and", "but", "or",
                "however", "also", "additionally", "furthermore", "moreover", "i", "we",
                "you", "there", "these", "those", "when", "where", "while", "with", "by",
                "from", "after", "before"}
        tok = self.processing_class
        for bi in range(input_ids.shape[0]):
            ans_idx = answer_mask[bi].nonzero(as_tuple=True)[0]
            if ans_idx.numel() == 0:
                continue
            surfaces = [tok.decode([int(t)]) for t in input_ids[bi][ans_idx]]
            prev_end = True
            for grp in _group_word_indices(surfaces):
                word = "".join(surfaces[j] for j in grp).strip()
                alpha = re.sub(r"[^A-Za-z]", "", word)
                if (len(alpha) >= 2 and alpha[0].isupper() and not prev_end
                        and word.lower() not in STOP):
                    for j in grp:
                        names[bi, ans_idx[j]] = True
                prev_end = word.endswith((".", "!", "?", ":", ";"))
        return names

    def _special_mask(self, input_ids):
        """Structural / end-of-sequence tokens (never a secret to forget)."""
        tok = self.processing_class
        if self._special_ids_cache is None:
            self._special_ids_cache = set(tok.all_special_ids)
        special = self._special_ids_cache
        mask = torch.zeros_like(input_ids, dtype=torch.bool)
        for tid in input_ids.unique().tolist():
            if int(tid) in special or not _SPECIAL_RE.sub("", tok.decode([int(tid)])).strip():
                mask |= input_ids == tid
        return mask

    def _eos_ids(self, device):
        """Terminator ids (eos / <|eot_id|> / <|endoftext|>) forbidden inside the generated
        answer span so the teacher cannot end-early into an empty completion."""
        if self._eos_ids_cache is None:
            tok = self.processing_class
            ids = set()
            for t in [tok.eos_token, "<|endoftext|>", "<|eot_id|>"]:
                if t:
                    ids.update(tok.encode(t, add_special_tokens=False))
            if tok.eos_token_id is not None:
                ids.add(int(tok.eos_token_id))
            self._eos_ids_cache = torch.tensor(sorted(ids), dtype=torch.long)
        return self._eos_ids_cache.to(device)

    @staticmethod
    def _otsu_threshold(vals, relax=0.0):
        """1-D Otsu split (maximise between-class variance); caller selects s >= thr."""
        xs, _ = torch.sort(vals)
        n = xs.numel()
        if n < 2 or float(xs[0]) == float(xs[-1]):
            return xs[0] if n else vals.new_tensor(0.0)
        total = xs.sum()
        csum = torch.cumsum(xs, 0)[:-1]
        cn = torch.arange(1, n, device=xs.device, dtype=xs.dtype)
        w0 = cn / n
        m0 = csum / cn
        m1 = (total - csum) / (n - cn)
        score = w0 * (1.0 - w0) * (m0 - m1) ** 2
        i = int(torch.argmax(score))
        thr = 0.5 * (xs[i] + xs[i + 1])
        return thr - relax * (thr - xs[0]) if relax > 0.0 else thr

    def _threshold_scores(self, s, answer_mask):
        if self.select_method == "tau":
            return (s >= self.tau) & answer_mask
        a_hat = torch.zeros_like(answer_mask)
        for bi in range(s.shape[0]):
            idx = answer_mask[bi].nonzero(as_tuple=True)[0]
            if idx.numel() == 0:
                continue
            vals = s[bi, idx]
            if self.select_method == "topk":
                k = max(1, int(round(self.topk_frac * idx.numel())))
                thr = torch.topk(vals, k).values.min()
            else:
                thr = self._otsu_threshold(vals, self.otsu_relax)
            a_hat[bi, idx[vals >= thr]] = True
        return a_hat

    @torch.no_grad()
    def _select_forget_positions(self, input_ids, answer_mask, attention_mask):
        """A_hat via PCSS (Alg. 1): average over ``sel_mc`` partial masks of the teacher
        prompt-dependence score, then threshold + drop question-echoes + drop specials."""
        b, l = answer_mask.shape
        device = input_ids.device
        prompt = self._prompt_mask(input_ids, answer_mask, attention_mask)
        gold = input_ids.unsqueeze(-1)

        s_sum = torch.zeros(b, l, device=device)
        cnt = torch.zeros(b, l, device=device)
        for _ in range(self.sel_mc):
            t = self.time_epsilon + (1 - self.time_epsilon) * torch.rand(b, device=device)
            p_mask = (1.0 - self.scheduler(t)).unsqueeze(1)
            m = (torch.rand((b, l), device=device) < p_mask) & answer_mask
            y = torch.where(m, self.mask_id, input_ids)
            log_cond = self._teacher_log_probs(y, attention_mask).gather(-1, gold).squeeze(-1)
            y_base = torch.where(prompt, self.mask_id, y)
            log_base = self._teacher_log_probs(y_base, attention_mask).gather(-1, gold).squeeze(-1)
            s_sum = s_sum + torch.where(m, log_cond - log_base, torch.zeros_like(s_sum))
            cnt = cnt + m.float()
        s = s_sum / cnt.clamp_min(1.0)

        a_hat = self._threshold_scores(s, answer_mask)
        a_hat = a_hat & ~self._special_mask(input_ids)
        if self.drop_question_overlap:
            a_hat = a_hat & ~self._question_overlap_mask(input_ids, answer_mask, prompt)
        return a_hat

    @torch.no_grad()
    def _generate_secret_free(self, input_ids, answer_mask, attention_mask, a_hat):
        """Frozen-teacher greedy denoise of a SECRET-FREE completed answer. Blank the entity
        names / identity in the query, mask the answer span (whole answer, or A_hat ∪ names
        for keep-answer), then fill it with the teacher's argmax on a confidence-topk
        schedule over ``gen_steps`` steps (EOS / filler suppressed). Returns [b, l]; only
        answer positions are meaningful. Deterministic (greedy) -- reproducible per example."""
        b, l = input_ids.shape
        mask_id = self.mask_id
        degrade = self._identity_mask(input_ids, answer_mask, attention_mask)

        hidden = None
        if self.keep_answer:
            names = self._answer_name_mask(input_ids, answer_mask, attention_mask)
            fill = (a_hat.bool() | names) & answer_mask
            if self.keep_subject_name:
                prompt = self._prompt_mask(input_ids, answer_mask, attention_mask)
                subject = self._question_overlap_mask(input_ids, answer_mask, prompt) & answer_mask
                hidden = subject & ~a_hat.bool()
                fill = fill & ~hidden
            zero = torch.zeros_like(answer_mask)
            gen_target = degrade | fill | (hidden if hidden is not None else zero)
        else:
            gen_target = degrade | answer_mask

        x = torch.where(gen_target, torch.full_like(input_ids, mask_id), input_ids)
        T = self.gen_steps
        suppress_ids = torch.cat([
            self._eos_ids(x.device),
            torch.tensor([i for i in (self.pad_id, mask_id) if i is not None],
                         dtype=torch.long, device=x.device),
        ]).unique()
        for step in range(T):
            mask_idx = (x == mask_id) & answer_mask
            if hidden is not None:
                mask_idx = mask_idx & ~hidden
            if not self._all_ranks_need(bool(mask_idx.any())):
                break
            n_remaining = mask_idx.sum(dim=1).float()
            steps_left = max(T - step, 1)
            n_unmask = (n_remaining / steps_left).ceil().long().clamp(min=1)
            logits = self._teacher_logits(x, attention_mask).float()
            logits[..., suppress_ids] = float("-inf")
            probs = F.softmax(logits, dim=-1)
            conf = probs.max(dim=-1).values
            pred = probs.argmax(dim=-1)
            for i in range(b):
                pos = mask_idx[i].nonzero(as_tuple=True)[0]
                if len(pos) == 0:
                    continue
                k = int(min(int(n_unmask[i].item()), len(pos)))
                _, top = conf[i, pos].topk(k, largest=True)
                x[i, pos[top]] = pred[i, pos[top]]
        if hidden is not None:
            x = torch.where(hidden, input_ids, x)
        return x

    def _gather_E(self, model):
        """Detached unembedding matrix E [vocab_size, d] in float32. Under DeepSpeed ZeRO-3
        the weight is sharded, so all-gather it with ``GatheredParameters`` (a COLLECTIVE --
        called unconditionally on every rank when repel is on). float32 is required: the
        e_hat = probs @ E contraction overflows to nan in bf16 (finite fwd, nan bwd)."""
        w = model.get_output_embeddings().weight
        if hasattr(w, "ds_shape"):
            import deepspeed

            with deepspeed.zero.GatheredParameters([w], modifier_rank=None):
                return w.detach().float()[: self.vocab_size].clone()
        return w.detach().float()[: self.vocab_size].clone()

    @staticmethod
    def _soft_emb(log_p, E):
        """Probability-weighted centroid e_hat = p @ E [n, d]."""
        return log_p.exp().to(E.dtype) @ E

    def _kernel(self, u, v, sigma=None, h=None):
        """RBF kernel reduced over d -> [n]. With h: exp(-||u-v||^2 / h) (SVGD form); else
        exp(-||u-v||^2 / 2 sigma^2). Sanitized + clamped so the backward stays finite even
        when the SVGD bandwidth collapses (near-coincident forget embeddings)."""
        sq = ((u - v) ** 2).sum(-1)
        sq = torch.nan_to_num(sq, nan=0.0, posinf=1e4, neginf=0.0).clamp(0.0, 1e4)
        if h is not None:
            expo = -sq / h
        else:
            s = self.sigma if sigma is None else sigma
            expo = -sq / (2.0 * s ** 2)
        return torch.exp(expo.clamp(min=-30.0))

    @staticmethod
    def _median_bandwidth(points):
        """SVGD median heuristic h = med^2 / log(n) for k(x,x')=exp(-||.||^2/h); None if
        degenerate. Floored so a collapsing median cannot drive the 1/h gradient to inf."""
        n = points.shape[0]
        if n < 2:
            return None
        with torch.no_grad():
            med = torch.pdist(points.float()).median()
            if not (float(med) > 0.0):
                return None
            return (med ** 2 / math.log(n)).clamp_min(1e-3)

    def _example_key(self, ids_row, attn_row):
        keep = attn_row.bool() if attn_row is not None else (ids_row != self.pad_id)
        return tuple(ids_row[keep].tolist())

    def _all_ranks_need(self, local_need):
        """Global OR of a per-rank boolean via all-reduce(MAX), so the decision to run the
        (collective) teacher forwards is identical on every rank. No-op single-process."""
        if dist.is_available() and dist.is_initialized():
            t = torch.tensor([1.0 if local_need else 0.0], device=self.accelerator.device)
            dist.all_reduce(t, op=dist.ReduceOp.MAX)
            return bool(t.item() > 0.0)
        return bool(local_need)

    def _cached_ahat_and_gen(self, input_ids, answer_mask, attention_mask):
        """Return (a_hat, gen_ans) [b, l] from the per-example cache, populating any missing
        entry first. The teacher work (A_hat selection + generation) runs on ALL ranks
        whenever ANY rank has an uncached example, keeping the collective sequence uniform."""
        b, l = answer_mask.shape
        keys = [
            self._example_key(
                input_ids[bi],
                attention_mask[bi] if attention_mask is not None else None,
            )
            for bi in range(b)
        ]
        local_miss = any(k not in self._gen_cache or k not in self._ahat_cache for k in keys)
        if self._all_ranks_need(local_miss):
            a_hat_fresh = self._select_forget_positions(input_ids, answer_mask, attention_mask)
            for bi, k in enumerate(keys):
                if k not in self._ahat_cache:
                    ans_pos = answer_mask[bi].nonzero(as_tuple=True)[0]
                    sel = a_hat_fresh[bi][ans_pos].nonzero(as_tuple=True)[0]
                    self._ahat_cache[k] = tuple(sel.tolist())
            a_hat_for_gen = self._build_ahat(keys, answer_mask)
            gen_fresh = self._generate_secret_free(
                input_ids, answer_mask, attention_mask, a_hat_for_gen
            )
            for bi, k in enumerate(keys):
                if k not in self._gen_cache:
                    ans_pos = answer_mask[bi].nonzero(as_tuple=True)[0]
                    self._gen_cache[k] = tuple(gen_fresh[bi][ans_pos].tolist())

        a_hat = self._build_ahat(keys, answer_mask)
        gen_ans = input_ids.clone()
        for bi, k in enumerate(keys):
            toks = self._gen_cache.get(k)
            if toks:
                ans_pos = answer_mask[bi].nonzero(as_tuple=True)[0]
                gen_ans[bi, ans_pos] = torch.tensor(
                    toks, device=gen_ans.device, dtype=gen_ans.dtype
                )
        return a_hat, gen_ans

    def _build_ahat(self, keys, answer_mask):
        a_hat = torch.zeros_like(answer_mask)
        for bi, k in enumerate(keys):
            ords = self._ahat_cache.get(k)
            if ords:
                ans_pos = answer_mask[bi].nonzero(as_tuple=True)[0]
                a_hat[bi, ans_pos[torch.tensor(ords, device=ans_pos.device)]] = True
        return a_hat

    def _build_context(self, model, forget_inputs):
        """Mask-independent per-batch context reused across every ``loss_mc`` draw: the
        preprocessed inputs, A_hat, the cached secret-free gen_ans, the frozen-teacher anchor
        logits ``tl_base`` (identity-blanked query + gen_ans answer, gold optionally
        suppressed at A_hat), and the gathered unembedding ``E``. Every teacher forward and
        the ``E`` all-gather live here (once per step, uniform across ranks); the per-draw
        path adds only a student forward."""
        prep = self._preprocess_inputs({
            "input_ids": forget_inputs["input_ids"],
            "labels": forget_inputs["labels"],
            "attention_mask": forget_inputs.get("attention_mask", None),
        })
        input_ids = prep["input_ids"]
        attention_mask = prep.get("attention_mask", None)
        answer_mask = prep["labels"] != -100

        a_hat, gen_ans = self._cached_ahat_and_gen(input_ids, answer_mask, attention_mask)

        degrade = self._identity_mask(input_ids, answer_mask, attention_mask)
        y_base = torch.where(degrade, self.mask_id, input_ids)
        y_base = torch.where(answer_mask, gen_ans, y_base)
        tl_base = self._teacher_logits(y_base, attention_mask).float()[..., : self.vocab_size]
        if self.suppress_gold:
            supp = a_hat.bool() & answer_mask
            if bool(supp.any()):
                bi_idx, pos_idx = supp.nonzero(as_tuple=True)
                tl_base[bi_idx, pos_idx, input_ids[bi_idx, pos_idx]] = float("-inf")

        E = self._gather_E(model) if self.repel_alpha > 0.0 else None

        return {
            "input_ids": input_ids,
            "attention_mask": attention_mask,
            "answer_mask": answer_mask,
            "a_hat": a_hat,
            "gen_ans": gen_ans,
            "tl_base": tl_base,
            "E": E,
        }

    def _sample_mask(self, input_ids, answer_mask):
        batch_size, seq_len = input_ids.shape
        timesteps = self.time_epsilon + (1 - self.time_epsilon) * torch.rand(
            batch_size, device=input_ids.device
        )
        mask_prob = 1.0 - self.scheduler(timesteps).unsqueeze(1)
        return (
            torch.rand((batch_size, seq_len), device=input_ids.device) < mask_prob
        ) & answer_mask

    def _distillation_loss(self, logits, ctx):
        answer_mask = ctx["answer_mask"]
        if self.repel_alpha >= 1.0 or not bool(answer_mask.any()):
            return logits.new_zeros(())

        if self.distill_mode == "teacher":
            with torch.no_grad():
                values, indices = ctx["tl_base"][answer_mask].topk(
                    self.distill_topk, dim=-1
                )
                target = torch.nan_to_num(F.softmax(values, dim=-1))
            log_probs = F.log_softmax(torch.nan_to_num(logits[answer_mask]), dim=-1)
            per_position = -(target * log_probs.gather(-1, indices).clamp(min=-30.0)).sum(-1)
        else:
            per_position = F.cross_entropy(
                torch.nan_to_num(logits[answer_mask]),
                ctx["gen_ans"][answer_mask],
                reduction="none",
            )

        if self.loss_d_ahat_weight == 1.0:
            return per_position.mean()
        weights = torch.where(
            ctx["a_hat"][answer_mask],
            per_position.new_full((), self.loss_d_ahat_weight),
            per_position.new_ones(()),
        )
        return (per_position * weights).sum() / weights.sum().clamp(min=1.0)

    def _repulsion_loss(self, logits, ctx, repel_mask):
        if self.repel_alpha <= 0.0 or ctx["E"] is None or not bool(repel_mask.any()):
            return logits.new_zeros(()), float("nan"), float("nan")

        embeddings = torch.nan_to_num(ctx["E"])
        student = torch.nan_to_num(
            self._soft_emb(F.log_softmax(logits[repel_mask], dim=-1), embeddings).float()
        )
        gold = embeddings[ctx["input_ids"][repel_mask]].float()
        anchor = torch.nan_to_num(
            self._soft_emb(
                F.log_softmax(ctx["tl_base"][repel_mask], dim=-1), embeddings
            ).float()
        )
        bandwidth = self._median_bandwidth(student) if self.median_bandwidth else None
        if bandwidth is None:
            bandwidth = student.new_tensor(2.0 * self.sigma_fallback ** 2)
        repel = self._kernel(student, gold, h=bandwidth)
        attract = self._kernel(student, anchor, sigma=self.sigma_anc)
        loss = (repel - self.gamma_anc * attract).mean()
        return loss, float(repel.mean()), float(attract.mean())

    @staticmethod
    def _draw_metrics(loss, distill_loss, repel_loss, repel_score, anchor_score, ctx, masked):
        answer_count = ctx["answer_mask"].sum().clamp_min(1)
        return {
            "repel_gendistill/loss": float(loss.detach()),
            "repel_gendistill/loss_d": float(distill_loss.detach()),
            "repel_gendistill/loss_f": float(repel_loss.detach()),
            "repel_gendistill/L_rep": repel_score,
            "repel_gendistill/L_anc": anchor_score,
            "repel_gendistill/selected_frac": float(
                ctx["a_hat"].sum().float() / answer_count
            ),
            "repel_gendistill/forget_masked": float((masked & ctx["a_hat"]).sum()),
            "repel_gendistill/mask_rate": float(masked.sum().float() / answer_count),
        }

    def _draw_loss(self, model, ctx):
        """Compute one random diffusion-mask draw over a cached batch context."""
        masked = self._sample_mask(ctx["input_ids"], ctx["answer_mask"])
        noised = torch.where(masked, self.mask_id, ctx["input_ids"])
        outputs = self._postprocess_outputs(
            model(input_ids=noised, attention_mask=ctx["attention_mask"])
        )
        logits = outputs.logits[..., : self.vocab_size].float()

        distill_loss = self._distillation_loss(logits, ctx)
        repel_loss, repel_score, anchor_score = self._repulsion_loss(
            logits, ctx, masked & ctx["a_hat"]
        )
        loss = (
            self.repel_alpha * repel_loss
            + (1.0 - self.repel_alpha) * distill_loss
            + 0.0 * logits.sum()
        )
        metrics = (
            self._draw_metrics(
                loss,
                distill_loss,
                repel_loss,
                repel_score,
                anchor_score,
                ctx,
                masked,
            )
            if model.training
            else {}
        )
        return loss, outputs, metrics

    def compute_loss(self, model, inputs, return_outputs=False, num_items_in_batch=None):
        """Average the forget loss over ``loss_mc`` mask draws, add the optional retain NLL.
        Used for evaluation and single-draw training; multi-draw training backprops each draw
        in ``training_step`` so activation memory stays at one student graph."""
        ctx = self._build_context(model, inputs["forget"])
        loss_sum, outputs, metrics = None, None, {}
        for _ in range(self.loss_mc):
            loss_i, outputs, metrics = self._draw_loss(model, ctx)
            loss_sum = loss_i if loss_sum is None else loss_sum + loss_i
        forget_loss = loss_sum / self.loss_mc

        retain_loss = self.optional_retain_loss(model, inputs)
        loss = self.gamma * forget_loss + self.alpha * retain_loss

        if model.training:
            metrics["repel_gendistill/loss"] = float(forget_loss.detach())
            self._pending_metrics.update(metrics)
        return (loss, outputs) if return_outputs else loss

    def training_step(self, model, inputs, num_items_in_batch=None):
        if self.loss_mc <= 1:
            loss = super().training_step(model, inputs, num_items_in_batch)
            if model.training and self.accelerator.sync_gradients and self._pending_metrics:
                self.log(self._pending_metrics)
                self._pending_metrics = {}
            return loss

        model.train()
        inputs = self._prepare_inputs(inputs)
        ctx = self._build_context(model, inputs["forget"])
        grad_state = self.accelerator.gradient_state
        step_sync = self.accelerator.sync_gradients
        n = self.loss_mc
        total = None
        last_metrics = {}
        for i in range(n):
            grad_state._set_sync_gradients(step_sync and i == n - 1)
            with self.compute_loss_context_manager():
                loss_i, _outputs, last_metrics = self._draw_loss(model, ctx)
                loss_i = self.gamma * loss_i / n
            self.accelerator.backward(loss_i)
            total = loss_i.detach() if total is None else total + loss_i.detach()
        grad_state._set_sync_gradients(step_sync)

        if model.training and step_sync:
            last_metrics["repel_gendistill/loss"] = float(total)
            self._pending_metrics.update(last_metrics)
            if self._pending_metrics:
                self.log(self._pending_metrics)
                self._pending_metrics = {}
        return total
